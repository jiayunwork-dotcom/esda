# 2. component mode basics: shapes and missing positions
# ----------------------------------------------------------------------
@check("basics: outputs at original positions, missing where expected")
def _():
    adj = adjacency()
    y = y_with_missing_bridge()
    for cls, stat in ((moran, "Is"), (getis, "Gs")):
        for w in (make_w(adj), make_graph(adj)):
            obj = cls(y, w)
            assert_missing_at(obj, stat)
            assert obj.p_sim.shape == (N,)
            assert np.isnan(obj.p_sim[MISSING_AT]).all()
            # the two-sided tail rule can count both tails of a degenerate
            # reference distribution, so p_sim is bounded by ~2
            assert ((obj.p_sim[COMP_A + COMP_B] > 0) & (obj.p_sim[COMP_A + COMP_B] <= 2)).all()
            assert obj.sim.shape == (PERMS, N)
            assert np.isnan(obj.sim[:, MISSING_AT]).all()
            assert np.isfinite(obj.sim[:, COMP_A + COMP_B]).all()
            assert (obj.component_labels_[COMP_A] == 0).all()
            assert (obj.component_labels_[COMP_B] == 1).all()
            assert obj.component_labels_[4] == -1  # the missing bridge


