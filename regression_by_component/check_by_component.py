# 13. a single zero-denominator cell loses only its own statistic
# ----------------------------------------------------------------------
@check("zero denominator: one cell missing, its value still sampled")
def _():
    # chain 0-1-2-3 with values summing to 5: the Gi denominator of site 3
    # (sum of the others) is zero; a second component (triangle 4-5-6) rides
    # along so the extraction below actually separates two components
    adj4 = adjacency()[:4][:, :4].toarray()
    tri = np.array([[0.0, 1.0, 1.0], [1.0, 0.0, 1.0], [1.0, 1.0, 0.0]])
    big = np.zeros((7, 7))
    big[:4, :4] = adj4
    big[4:, 4:] = tri
    adj_big = sparse.csr_matrix(big)
    y = np.array([1.0, -1.0, 0.0, 5.0, 2.0, 4.0, 6.0])
    lg = getis(y, make_w(adj_big), transform="B", star=False)
    assert np.isnan(lg.Gs[3]) and np.isnan(lg.p_sim[3])
    assert np.isnan(lg.sim[:, 3]).all()
    np.testing.assert_allclose(lg.Gs[0], -1 / 4, rtol=1e-12)
    np.testing.assert_allclose(lg.Gs[1], 1 / 6, rtol=1e-12)
    np.testing.assert_allclose(lg.Gs[2], 4 / 5, rtol=1e-12)
    assert np.isfinite(lg.p_sim[[0, 1, 2]]).all()
    # Gi* denominator is the component sum: no zero-denominator cell here
    lg_star = getis(y, make_w(adj_big), transform="B", star=True)
    assert np.isfinite(lg_star.Gs).all()
    # recomputing the component alone reproduces everything, proving the
    # zero-denominator cell's value still feeds the other sites' draws
    alone = getis(y[:4], make_w(sparse.csr_matrix(adj4)), transform="B", star=False)
    np.testing.assert_array_equal(alone.Gs, lg.Gs[:4])
    np.testing.assert_array_equal(alone.sim, lg.sim[:, :4])
    np.testing.assert_array_equal(alone.p_sim, lg.p_sim[:4])


