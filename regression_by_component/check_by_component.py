    adj_da = adj_d[COMP_A][:, COMP_A]
    alone = moran(Y_FULL[COMP_A], make_w(adj_da))
    np.testing.assert_array_equal(lm.Is[COMP_A], alone.Is)
    np.testing.assert_array_equal(lm.sim[:, COMP_A], alone.sim)
    np.testing.assert_array_equal(lm.p_sim[COMP_A], alone.p_sim)
