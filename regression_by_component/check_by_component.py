    np.testing.assert_allclose(lm_pre.Is, lm.Is, rtol=1e-12)
    # binary transform works too
    lm_b = moran(y, make_w(adjacency()), transformation="b")
    assert_missing_at(lm_b, "Is")
    lg = getis(y, make_w(adjacency()), transform="R")
    np.testing.assert_allclose(lg.Gs[1], (0.5 * 10 + 0.5 * 11) / (46 - 12), rtol=1e-12)


