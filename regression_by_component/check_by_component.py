# 12. Gi and Gi* are handled on the retained weights
# ----------------------------------------------------------------------
@check("star: Gi and Gi* denominators and self-weights per component")
def _():
    y = y_with_missing_bridge()
    adj = adjacency()
    # manual values on component A = [10, 12, 11, 13], sum 46, chain 0-1-2-3
    gi = getis(y, make_w(adj), transform="B", star=False)
    np.testing.assert_allclose(gi.Gs[0], 12 / 36, rtol=1e-12)
    np.testing.assert_allclose(gi.Gs[1], 21 / 34, rtol=1e-12)
    np.testing.assert_allclose(gi.Gs[3], 11 / 33, rtol=1e-12)
    gistar = getis(y, make_w(adj), transform="B", star=True)
    np.testing.assert_allclose(gistar.Gs[0], 22 / 46, rtol=1e-12)
    np.testing.assert_allclose(gistar.Gs[1], 33 / 46, rtol=1e-12)
    assert not np.allclose(gi.Gs[COMP_A], gistar.Gs[COMP_A])
    # star=None infers from the retained diagonal
    adj_loop = adjacency(self_loops=(0,))
    inferred = getis(y, make_w(adj_loop), transform="B", star=None)
    assert inferred.star
    np.testing.assert_allclose(inferred.Gs[0], (12 + 10) / 46, rtol=1e-12)
    np.testing.assert_allclose(inferred.Gs[1], 21 / 46, rtol=1e-12)
    # star=False drops an existing diagonal on the retained weights
    dropped = getis(y, make_w(adj_loop), transform="B", star=False)
    np.testing.assert_allclose(dropped.Gs[0], 12 / 36, rtol=1e-12)
    # Gi* extraction consistency (self-weight travels with the component)
    adj_loop_a = adj_loop[COMP_A][:, COMP_A]
    alone = getis(Y_FULL[COMP_A], make_w(adj_loop_a), transform="B", star=True)
    full = getis(y, make_w(adj_loop), transform="B", star=True)
    np.testing.assert_array_equal(full.Gs[COMP_A], alone.Gs)
    np.testing.assert_array_equal(full.sim[:, COMP_A], alone.sim)
    np.testing.assert_array_equal(full.p_sim[COMP_A], alone.p_sim)


