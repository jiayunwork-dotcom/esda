# 8. both simulation-saving modes give the same inference
# ----------------------------------------------------------------------
@check("keep_simulations: p_sim identical with and without saved sims")
def _():
    y = y_with_missing_bridge()
    lm_keep = moran(y, make_w(adjacency()), keep_simulations=True)
    lm_drop = moran(y, make_w(adjacency()), keep_simulations=False)
    np.testing.assert_allclose(lm_keep.p_sim, lm_drop.p_sim, rtol=1e-6)
    assert lm_drop.sim is None and lm_drop.rlisas is None
    assert lm_keep.sim.shape == (PERMS, N)
    lg_keep = getis(y, make_w(adjacency()), keep_simulations=True)
    lg_drop = getis(y, make_w(adjacency()), keep_simulations=False)
    np.testing.assert_allclose(lg_keep.p_sim, lg_drop.p_sim, rtol=1e-6)
    assert lg_drop.rGs.shape == (1, 1)
    assert not hasattr(lg_drop, "sim")
    # streaming p_sim matches a fresh tail count on the stored sims
    for obj, stat in ((lm_keep, "Is"), (lg_keep, "Gs")):
        recomputed = calculate_significance(
            getattr(obj, stat), obj.sim.T, alternative=ALT
        )
        np.testing.assert_allclose(
            np.asarray(recomputed)[np.isfinite(obj.p_sim)],
            obj.p_sim[np.isfinite(obj.p_sim)],
            rtol=1e-6,
        )


