# 11. row standardisation acts on the retained edges
# ----------------------------------------------------------------------
@check("transform: row standardisation is recomputed on retained edges")
def _():
    y = y_with_missing_bridge()
    lm = moran(y, make_w(adjacency()), transformation="r")
    rowsum = np.asarray(lm.w.sparse.sum(axis=1)).flatten()
    nonempty = np.asarray((lm.w.sparse != 0).sum(axis=1)).flatten() > 0
