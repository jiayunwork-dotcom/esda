# 15b. boundary cases: size-3 component, weighted edges, float star
# ----------------------------------------------------------------------
@check("boundaries: size-3 component works; weighted edges; float star")
def _():
    # a triangle (exactly three observed sites) is a valid component
    tri = np.array(
        [[0.0, 1.0, 1.0], [1.0, 0.0, 1.0], [1.0, 1.0, 0.0]]
    )
    y3 = np.array([1.0, 2.0, 4.0])
    for cls, stat in ((moran, "Is"), (getis, "Gs")):
        obj = cls(y3, make_w(sparse.csr_matrix(tri)))
        assert np.isfinite(getattr(obj, stat)).all()
        assert np.isfinite(obj.p_sim).all()
    # weighted edges: statistics follow the weights, extraction is stable
    adj_w = adjacency().astype(float)
    adj_w[0, 1] = adj_w[1, 0] = 2.5
    adj_w[7, 8] = adj_w[8, 7] = 0.25
    y = y_with_missing_bridge()
    lm_o = moran(y, make_w(adj_w), transformation="o")
    np.testing.assert_allclose(
        lm_o.w.sparse[0, 1], 2.5, rtol=1e-12
    )  # weights survive masking
    lm_r = moran(y, make_w(adj_w), transformation="r")
    np.testing.assert_allclose(
        lm_r.w.sparse[1, 0], 2.5 / 3.5, rtol=1e-12
    )  # row standardisation uses the retained weights
    lm = moran(y, make_w(adj_w), transformation="b")
    alone = moran(Y_FULL[COMP_A], make_w(adj_w[COMP_A][:, COMP_A]), transformation="b")
    np.testing.assert_array_equal(lm.Is[COMP_A], alone.Is)
    np.testing.assert_array_equal(lm.sim[:, COMP_A], alone.sim)
    # star as an explicit float self-weight: matches the old estimator run
    # on the extracted component (transform 'B' binarises the self-weight)
    lg = getis(y, make_w(adjacency()), transform="B", star=0.5)
    lg_default = G_Local(
        Y_FULL[COMP_A],
        make_w(adjacency()[COMP_A][:, COMP_A]),
        transform="B",
        star=0.5,
        permutations=PERMS,
        seed=SEED,
        alternative=ALT,
    )
    np.testing.assert_array_equal(lg.Gs[COMP_A], lg_default.Gs)


