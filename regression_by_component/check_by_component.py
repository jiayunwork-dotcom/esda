# 10. directed edges: one non-zero edge joins a component
# ----------------------------------------------------------------------
@check("directed: single one-way edges connect; statistics keep directions")
def _():
    adj_d = adjacency(directed=True)
    y = y_with_missing_bridge()
    lm = moran(y, make_w(adj_d))
