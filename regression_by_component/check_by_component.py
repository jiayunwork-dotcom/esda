# 14. self-loops: they join statistics but not components
# ----------------------------------------------------------------------
@check("self-loops: counted in statistics, useless for connectivity")
def _():
    # chain 0-1-2-3 plus node 4 with only a self-loop; self-loop on node 0
    adj = np.zeros((5, 5))
    for i, j in [(0, 1), (1, 2), (2, 3)]:
        adj[i, j] = adj[j, i] = 1.0
    adj[0, 0] = 1.0
    adj[4, 4] = 1.0
    adj = sparse.csr_matrix(adj)
    y = np.array([1.0, 2.0, 3.0, 4.0, 9.0])
    lg = getis(y, make_w(adj), transform="B", star=None)
    assert lg.star  # inferred from the retained diagonal
    assert np.isnan(lg.Gs[4])  # alone in its component
    np.testing.assert_allclose(lg.Gs[0], (2 + 1) / 10, rtol=1e-12)
    np.testing.assert_allclose(lg.Gs[1], (1 + 3) / 10, rtol=1e-12)
    lm = moran(y, make_w(adj))
    assert np.isnan(lm.Is[4])
    assert np.isfinite(lm.Is[:4]).all()
    alone = moran(y[:4], make_w(adj[:4][:, :4]))
    np.testing.assert_array_equal(lm.Is[:4], alone.Is)
    np.testing.assert_array_equal(lm.sim[:, :4], alone.sim)


