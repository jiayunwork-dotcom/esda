"""Regression checks for the by-component (connected-component) mode of
``Moran_Local`` and ``G_Local``.

Run with the project environment from the repository root:

    python regression_by_component/check_by_component.py

The script

1. recomputes the old whole-graph entry points and requires them to match
   ``reference_default_mode.npz`` (generated by ``make_reference.py`` with
   an unmodified esda), and
2. exercises the by-component mode on a handmade graph: a missing bridge
   node splits two river segments, one component is recomputed on its own,
   the other component is perturbed, and both W and Graph inputs, directed
   edges, row standardisation, Gi/Gi*, degenerate components, both
   simulation-saving modes and serial/parallel execution are checked.

Exit status is 0 only if every check passes.
"""

import sys
import warnings
from pathlib import Path

import numpy as np
from handmade import (
    COMP_A,
    COMP_B,
    MISSING_AT,
    N,
    Y_FULL,
    adjacency,
    make_graph,
    make_w,
    permute_table,
    y_with_missing_bridge,
)
from scipy import sparse

from esda import G_Local, Moran_Local
from esda.significance import calculate_significance

HERE = Path(__file__).parent
SEED = 12345
PERMS = 99
ALT = "two-sided"

FAILURES = []
PASSES = []


def check(name):
    def deco(fn):
        try:
            with warnings.catch_warnings():
                warnings.simplefilter("ignore", DeprecationWarning)
                fn()
        except Exception as exc:  # noqa: BLE001
            FAILURES.append((name, exc))
            print(f"FAIL {name}: {type(exc).__name__}: {exc}")
        else:
            PASSES.append(name)
            print(f"pass {name}")

    return deco


def moran(y, w, **kw):
    kw.setdefault("permutations", PERMS)
    kw.setdefault("seed", SEED)
    kw.setdefault("alternative", ALT)
    kw.setdefault("by_component", True)
    return Moran_Local(y, w, **kw)


def getis(y, w, **kw):
    kw.setdefault("permutations", PERMS)
    kw.setdefault("seed", SEED)
    kw.setdefault("alternative", ALT)
    kw.setdefault("by_component", True)
    return G_Local(y, w, **kw)


def assert_missing_at(obj, stat_name):
    stat = getattr(obj, stat_name)
    assert stat.shape == (N,), f"{stat_name} shape {stat.shape}"
    assert np.isnan(stat[MISSING_AT]).all(), f"{stat_name} not NaN at {MISSING_AT}"
    assert np.isfinite(stat[COMP_A + COMP_B]).all(), f"{stat_name} NaN inside A/B"


# ----------------------------------------------------------------------
# 1. old entry points unchanged
# ----------------------------------------------------------------------
@check("reference: default whole-graph entry points unchanged")
def _():
    ref = np.load(HERE / "reference_default_mode.npz")
    adj = adjacency()
    w, g = make_w(adj), make_graph(adj)
    y = Y_FULL
    moran_attrs = ["z", "Is", "q", "p_sim", "EI", "VI", "EIc", "VIc", "EI_sim", "z_sim"]
    g_attrs = ["Gs", "EGs", "VGs", "Zs", "p_sim", "EG_sim", "z_sim"]
    runs = {
        "moran_w": Moran_Local(y, w, transformation="r", permutations=PERMS,
                               seed=SEED, alternative=ALT),
        "moran_g": Moran_Local(y, g, transformation="r", permutations=PERMS,
                               seed=SEED, alternative=ALT),
        "moran_par": Moran_Local(y, make_w(adj), transformation="r",
                                 permutations=PERMS, seed=SEED, n_jobs=2,
                                 alternative=ALT),
        "g_w": G_Local(y, w, transform="R", permutations=PERMS, seed=SEED,
                       alternative=ALT),
        "g_star_w": G_Local(y, w, transform="R", star=True, permutations=PERMS,
                            seed=SEED, alternative=ALT),
        "g_g": G_Local(y, g, transform="B", permutations=PERMS, seed=SEED,
                       alternative=ALT),
    }
    attrs = {"moran_w": moran_attrs, "moran_g": moran_attrs,
             "moran_par": ["p_sim"], "g_w": g_attrs, "g_star_w": g_attrs,
             "g_g": g_attrs}
    for key, obj in runs.items():
        for name in attrs[key]:
            np.testing.assert_array_equal(
                np.asarray(getattr(obj, name), dtype=np.float64),
                ref[f"{key}.{name}"],
                err_msg=f"{key}.{name}",
            )


